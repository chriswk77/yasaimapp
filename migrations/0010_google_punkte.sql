-- A DATA TRANSFER OF ONE INSTALLATION — nothing to do anywhere else.
--
-- This file carried one account's first find spots (an import from Google
-- Maps, eight lists and their points) from a local database to the live
-- server, at a time when that server had no command line to run
-- admin/takeout_import.php on. It inserted nothing where no administrator
-- existed, so a fresh installation never got anything from it.
--
-- WHY THE FILE IS STILL HERE: the migrations' file names are the ledger of
-- what an installation has applied (includes/migrations.php). A name that
-- vanished would be a gap in the numbering nobody could explain, and on an
-- installation that had applied it a line in the ledger without a file.
--
-- WHY ITS STATEMENTS ARE GONE (22.11.2026, the day the repository went
-- public): they were one person's find spots with their coordinates — data
-- that has no business in a repository others read. The pass before
-- publishing had looked for names, credentials and installation ids and
-- missed it.
--
-- Where it had run, it has run: the ledger knows it by its name and never
-- looks into it again. Everywhere else it is applied as what it now is —
-- nothing.
