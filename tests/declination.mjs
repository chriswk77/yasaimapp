console.log('The hundred published test points (to ±0.01°):');
let worst = 0, misses = 0;
for (const [year, alt, lat, lon, want] of VALUES) {
    const got = declination(lat, lon, alt, year);
    const off = Math.abs(got - want);
    worst = Math.max(worst, off);
    if (off > 0.01 + 1e-9) {
        misses++;
        console.log(`  FAILED: ${year} ${alt} km ${lat}/${lon}: ${got.toFixed(3)} instead of ${want}`);
    }
}
check(misses === 0, `all ${VALUES.length} within a hundredth (worst ${worst.toFixed(4)}°)`);

console.log('The clock:');
check(Math.abs(decimalYear(new Date(Date.UTC(2026, 0, 1))) - 2026) < 1e-9, 'the first of January is the whole year');
check(Math.abs(decimalYear(new Date(Date.UTC(2026, 6, 2, 12))) - 2026.5) < 0.002, 'the second of July at noon is about half the year');

console.log('A place we know:');
